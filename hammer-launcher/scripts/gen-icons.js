const out = {};
for (const [name, file] of Object.entries(ICONS)) {
  const raw = fs.readFileSync(path.join(FA, `${file}.svg`), 'utf8');
  const viewBox = raw.match(/viewBox="([^"]+)"/)[1];
  const d = [...raw.matchAll(/<path[^>]*d="([^"]+)"/g)].map((m) => m[1]);
  out[name] = [viewBox, d];
}
